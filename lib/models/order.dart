class Order {
  final String personnelCode;
  final String name;
  final String gender;
  final String orgUnitCode;
  final String orgUnitName;
  final String teachingType;
  final String level;
  final String teachingGroup;
  final String orgUnitType;
  final String hours;
  final String fromDate;
  final String toDate;
  final String teachingField;
  final String post;

  Order({
    required this.personnelCode,
    required this.name,
    required this.gender,
    required this.orgUnitCode,
    required this.orgUnitName,
    required this.teachingType,
    required this.level,
    required this.teachingGroup,
    required this.orgUnitType,
    required this.hours,
    required this.fromDate,
    required this.toDate,
    required this.teachingField,
    required this.post,
  });
}
